class AssignmentOperators{
	public static void main(String args[]){
		int x=10;
		System.out.println("X= "+x);
		x+=5;
		System.out.println("X+=5: "+x);
		x-=2;
		System.out.println("X-=2: "+x);
		x*=3;
		System.out.println("X*=3: "+x);
		x/=4;
		System.out.println("X/=4: "+x);
		x%=5;
		System.out.println("X%=5: "+x);
	}
}